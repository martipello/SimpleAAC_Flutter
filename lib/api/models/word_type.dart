enum WordType {
  /// High-frequency core vocabulary — I, want, help, stop, yes, no, more...
  core,

  /// Nouns organised by sub-category — food, animals, places, people...
  things,

  /// Verbs — eat, drink, play, sleep, go, help...
  actions,

  /// Adjectives and adverbs — big, red, happy, fast...
  describe,

  /// Feelings, greetings, phrases, questions
  social,

  /// Pronouns, conjunctions, prepositions, suffixes
  grammar,
}
